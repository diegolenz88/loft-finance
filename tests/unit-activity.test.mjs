import assert from 'node:assert/strict';
import {activeUnits,activeStudioCount,inactiveUnits,withUnitActivity,entryUnitOptions,unitLabel,apply,demoLedger,emptyLedger,metrics,paid} from '../lib/finance.ts';

const archived=['Loft 09','Loft 10','Loft 11','Loft 12'];
const config=structuredClone(demoLedger().config);
delete config.inactiveUnits;
const original=structuredClone(config);
assert.equal(activeStudioCount(config),8);
assert.equal(activeUnits(config).length,9);
assert.ok(activeUnits(config).includes('Áreas comuns'));
assert.deepEqual(inactiveUnits(config),archived);
assert.deepEqual(config,original,'Reading legacy activity must never mutate source data');
assert.deepEqual(withUnitActivity(withUnitActivity(config)),withUnitActivity(config));
assert.equal(activeStudioCount({...config,inactiveUnits:[]}),12,'Explicit reactivation overrides compatibility defaults');

let sequence=0;
const run=(state,type,data,admin=true)=>apply(state,{id:'units-'+(++sequence),type,data},'owner@example.com',admin);
let state=emptyLedger({...config,inactiveUnits:[]});
const expense={kind:'expense',description:'Obra com histórico',party:'Fornecedor',document:'NF 1',category:config.categories[0],stage:config.stages[0],units:{'Loft 09':50,'Loft 01':50},amount:100000,fees:0,date:'2026-09-01',due:'2026-10-06',note:'Histórico',planned:false};
state=run(state,'expense_plan',{expense,installments:2,downPayment:20000,downPaymentDue:'2026-09-01'});
const paymentEntry=state.entries[0].id,editEntry=state.entries[1].id;
state=run(state,'attachment',{entry:paymentEntry,file:{id:'receipt-original',name:'comprovante.pdf'}});
state=run(state,'move',{type:'pay',entry:paymentEntry,source:'direct:a:capital',amount:10000,date:'2026-09-01',note:'Pagamento parcial'});
state=run(state,'entry',{...expense,kind:'revenue',units:{'Loft 12':100},description:'Receita antiga'});
const revenueId=state.entries.at(-1).id;
const before=structuredClone(state),beforeMetrics=metrics(state);
state=run(state,'config',{...state.config,inactiveUnits:archived});
assert.equal(activeStudioCount(state.config),8);
assert.deepEqual(state.entries,before.entries,'No entries, shares, attachments or installment snapshots change');
assert.deepEqual(state.moves,before.moves);
assert.deepEqual(state.audit.slice(1),before.audit);
assert.deepEqual(metrics(state),beforeMetrics,'Activity cannot change financial totals or partner balances');
assert.match(state.audit[0].description,/Unidades inativadas: Loft 09, Loft 10, Loft 11, Loft 12/);
assert.equal(unitLabel(state.config,'Loft 09'),'Loft 09 (inativo)');
assert.ok(!entryUnitOptions(state.config).includes('Loft 09'));
assert.ok(entryUnitOptions(state.config,state.entries[0]).includes('Loft 09'));
assert.ok(!entryUnitOptions(state.config,state.entries[0]).includes('Loft 10'));

for(const kind of ['expense','revenue']){
 assert.throws(()=>run(state,'entry',{...expense,kind}),/inativo/);
 assert.throws(()=>run(state,'batch',[{id:'inactive-batch',type:'entry',data:{...expense,kind}}]),/inativo/);
}
const unchanged=structuredClone(state);
assert.throws(()=>run(state,'expense_plan',{expense,installments:3,downPayment:20000,downPaymentDue:'2026-09-01'}),/inativo/);
assert.deepEqual(state,unchanged,'Rejected plans must remain atomic');
const originalEntry=state.entries.find(e=>e.id===editEntry);
state=run(state,'entry',{...originalEntry,due:'2026-10-20'});
assert.deepEqual(state.entries.find(e=>e.id===editEntry).units,originalEntry.units);
assert.deepEqual(state.entries.find(e=>e.id===editEntry).paymentPlan,originalEntry.paymentPlan);
assert.throws(()=>run(state,'entry',{...originalEntry,units:{'Loft 09':100}}),/inativo/);
assert.throws(()=>run(state,'entry',{...originalEntry,units:{'Loft 10':50,'Loft 01':50}}),/inativo/);
assert.throws(()=>run(state,'entry',{...originalEntry,kind:'revenue'}),/Preserve o tipo/);
state=run(state,'move',{type:'pay',entry:paymentEntry,source:'direct:a:capital',amount:10000,date:'2026-10-06',note:'Quitar pendência de unidade inativa'});
assert.equal(paid(state,state.entries[0]),20000);
state=run(state,'move',{type:'receive',entry:revenueId,source:'project',account:'Conta principal',gross:100000,fee:0,reserve:0,amount:100000,date:'2026-10-06',note:'Receber pendência de unidade inativa'});
assert.equal(paid(state,state.entries.find(e=>e.id===revenueId)),100000);
assert.throws(()=>run(state,'config',{...state.config,units:state.config.units.filter(u=>u!=='Loft 12'),inactiveUnits:archived.filter(u=>u!=='Loft 12')}),/Preserve contas e unidades/);
assert.throws(()=>run(state,'config',{...state.config,inactiveUnits:[]},false),/administradores/);
assert.throws(()=>run(state,'config',{...state.config,inactiveUnits:['Não existe']}),/inválidas/);
assert.throws(()=>run(state,'config',{...state.config,inactiveUnits:['Áreas comuns']}),/áreas comuns/);
assert.throws(()=>run(state,'config',{...state.config,inactiveUnits:['Loft 09','Loft 09']}),/inválidas/);
assert.throws(()=>run(state,'config',{...state.config,inactiveUnits:state.config.units.filter(u=>u!=='Áreas comuns')}),/pelo menos um studio/);
state=run(state,'config',{...state.config,inactiveUnits:[]});
assert.equal(activeStudioCount(state.config),12);
assert.match(state.audit[0].description,/Unidades reativadas/);
const legacyClientConfig={...state.config};delete legacyClientConfig.inactiveUnits;
state=run(state,'config',legacyClientConfig);
assert.equal(activeStudioCount(state.config),12,'Old clients must preserve saved activity settings');
state=run(state,'entry',expense);
assert.deepEqual(state.entries.at(-1).units,expense.units);
state=run(state,'config',{...state.config,inactiveUnits:archived});
const shared=Object.fromEntries(activeUnits(state.config).filter(u=>u!=='Áreas comuns').map(u=>[u,12.5]));
state=run(state,'expense_plan',{expense:{...expense,units:shared},installments:3,downPayment:20000,downPaymentDue:'2026-09-01'});
assert.ok(state.entries.slice(-4).every(e=>Object.keys(e.units).length===8));
const reloaded=JSON.parse(JSON.stringify(state));
assert.equal(activeStudioCount(reloaded.config),8);
assert.deepEqual(metrics(reloaded),metrics(state));
assert.deepEqual(reloaded.entries.map(e=>({id:e.id,units:e.units,amount:e.amount,attachments:e.attachments})),state.entries.map(e=>({id:e.id,units:e.units,amount:e.amount,attachments:e.attachments})));
assert.deepEqual(reloaded.moves,state.moves);
console.log('PASS: 8 active studios, legacy compatibility, immutable financial history, inactive-entry guards, historical settlements, reactivation, and 8-way installments.');
